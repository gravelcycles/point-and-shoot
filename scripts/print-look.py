#!/usr/bin/env python3
"""Tools for the Print look (see PointAndShoot/Editor/FilmModel.swift).

  print-look.py export-swift
      Regenerate PointAndShoot/Editor/FilmStock+Print.swift from scripts/print-stock.json.

  print-look.py preview IMG.dng [...] [--ev 0.0] [--out DIR]
      Render DNGs through the reference model (scene-linear develop, like the app).

  print-look.py parity
      Compile FilmModel.swift with swiftc (any platform) and check it computes exactly
      what filmmodel.py does. Run after any change to either.

  print-look.py fit PAIRS_DIR [--same-raw] [--out scripts/print-stock.json]
      Tune the look to reference renders. PAIRS_DIR holds NAME.dng + NAME.jpg (or .heic /
      .png) pairs of the same scene: the DNG from Point & Shoot (Zero or RAW, DNG kept),
      the JPEG/HEIC from the app you're matching. Best: the reference app's own export of
      the *same* RAW (pixel-aligned). Otherwise shoot both from a tripod, same lens.
      Fits the look's tone, balance, crossover and color (plus per-pair exposure and white
      balance, or with --same-raw one shared exposure offset); writes a new stock JSON.
      Then run export-swift.

Needs: numpy scipy pillow rawpy opencv-python-headless (pillow-heif for .heic).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import filmmodel as F  # noqa: E402

STOCK = os.path.join(HERE, "print-stock.json")
SWIFT = os.path.join(HERE, "..", "PointAndShoot", "Editor", "FilmStock+Print.swift")


# --- export-swift ----------------------------------------------------------------------

def _arr(v, per_line=8, indent="            "):
    items = [f"{float(x):.6g}" for x in v]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n" + ",\n".join(indent + l for l in lines) + ",\n" + indent[:-4] + "]"


def export_swift(stock_path=STOCK, out=SWIFT):
    s = F.load_stock(stock_path)

    def curve(c):
        return f"FilmCurve(\n            x: {_arr(c['x'], indent='                ')},\n            y: {_arr(c['y'], indent='                ')})"

    neg = [curve(c) for c in s["negative"]]
    prn = [curve(c) for c in s["print"]]
    same_neg = all(c == s["negative"][0] for c in s["negative"])
    same_prn = all(c == s["print"][0] for c in s["print"])
    hs = s["halation_spread"]
    lines = [
        "// GENERATED by scripts/print-look.py export-swift from scripts/print-stock.json.",
        "// Don't edit by hand: change the JSON (or refit it) and regenerate.",
        "",
        "extension FilmStock {",
        f"    /// {s['name']}: " + s.get("about", "").replace("\n", " "),
        "    static let printLook: FilmStock = {",
    ]
    if same_neg:
        lines.append(f"        let negative = {neg[0]}")
    if same_prn:
        lines.append(f"        let printCurve = {prn[0]}")
    lines += [
        "        return FilmStock(",
        f"            exposure: {s.get('exposure', 0.0)},",
        f"            sensitivity: {_arr(s['sensitivity'], 3, '                ')},",
        "            negative: " + ("[negative, negative, negative]," if same_neg else "[" + ", ".join(neg) + "],"),
        "            print: " + ("[printCurve, printCurve, printCurve]," if same_prn else "[" + ", ".join(prn) + "],"),
        f"            printer: {[float(v) for v in s['printer']]},",
        f"            crossover: {[float(v) for v in s['crossover']]},",
        f"            crosstalk: {_arr(s['crosstalk'], 3, '                ')},",
        f"            display: {_arr(s['display'], 3, '                ')},",
        f"            halation: {[float(v) for v in s['halation']]},",
        "            halationSpread: .init(",
        f"                threshold: {hs['threshold']}, boost: {hs['boost']},",
        f"                displayThreshold: {hs['display_threshold']}, displayBoost: {hs['display_boost']},",
        f"                sigmas: {[float(v) for v in hs['sigmas']]}, weights: {[float(v) for v in hs['weights']]}),",
        f"            grainDensity: {s['grainDensity']},",
        f"            grainChroma: {s['grainChroma']},",
        f"            grainSize: {s['grain_size']})",
        "    }()",
        "}",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(out))


# --- DNG develop (like CIRAWFilter with no tone curve) ---------------------------------

def develop_linear(path, max_side=None):
    import rawpy
    from PIL import Image
    with rawpy.imread(path) as r:
        rgb = r.postprocess(gamma=(1, 1), no_auto_bright=True, output_bps=16, use_camera_wb=True,
                            output_color=rawpy.ColorSpace.sRGB, highlight_mode=rawpy.HighlightMode.Blend)
    img = rgb.astype(np.float32) / 65535.0
    try:  # DNG BaselineExposure, which CIRAWFilter applies by default
        from PIL import Image as _I
        be = _I.open(path).tag_v2.get(50730)
        if be is not None:
            img *= 2.0 ** float(be)
    except Exception:
        pass
    if max_side and max(img.shape[:2]) > max_side:
        s = max_side / max(img.shape[:2])
        h, w = int(img.shape[0] * s), int(img.shape[1] * s)
        img = np.stack([np.asarray(Image.fromarray(img[..., c]).resize((w, h), Image.BOX)) for c in range(3)], -1)
    return img.astype(np.float64)


def save_p3(img_lin_p3, path):
    from PIL import Image
    Image.fromarray((F.encode_srgb(img_lin_p3) * 255 + 0.5).astype(np.uint8)).save(path, quality=93)


def preview(paths, ev, out_dir, stock_path=STOCK):
    st = F.load_stock(stock_path)
    os.makedirs(out_dir, exist_ok=True)
    for p in paths:
        lin = develop_linear(p, max_side=2400)
        out = F.render(lin, st, exposure_ev=ev)
        name = os.path.splitext(os.path.basename(p))[0]
        save_p3(out, os.path.join(out_dir, f"{name}-print.jpg"))
        print("wrote", os.path.join(out_dir, f"{name}-print.jpg"))


# --- fit -------------------------------------------------------------------------------

P3_TO_XYZ = np.array([[0.4865709, 0.2656677, 0.1982173], [0.2289746, 0.6917385, 0.0792869],
                      [0.0, 0.0451134, 1.0439444]])


def oklab_p3(rgb):
    M1 = np.array([[0.8189330101, 0.3618667424, -0.1288597137], [0.0329845436, 0.9293118715, 0.0361456387],
                   [0.0482003018, 0.2643662691, 0.6338517070]])
    M2 = np.array([[0.2104542553, 0.7936177850, -0.0040720468], [1.9779984951, -2.4285922050, 0.4505937099],
                   [0.0259040371, 0.7827717662, -0.8086757660]])
    return np.cbrt(np.maximum(rgb @ P3_TO_XYZ.T @ M1.T, 0)) @ M2.T


def load_reference(path, long_side):
    """Reference render → linear Display P3 (honours an embedded ICC profile)."""
    from PIL import Image, ImageCms
    if path.lower().endswith((".heic", ".heif")):
        import pillow_heif
        pillow_heif.register_heif_opener()
    im = Image.open(path)
    icc = im.info.get("icc_profile")
    im = im.convert("RGB")
    if icc:
        import io
        src = ImageCms.ImageCmsProfile(io.BytesIO(icc))
        name = ImageCms.getProfileDescription(src).strip().lower()
        if "p3" not in name:
            # Convert sRGB-family (or anything else) to P3 through littleCMS.
            p3 = ImageCms.createProfile("sRGB")  # fallback: treat as sRGB primaries
            im = ImageCms.profileToProfile(im, src, p3)
            arr = F.decode_srgb(np.asarray(im).astype(np.float64) / 255)
            srgb_to_p3 = np.array([[0.822462, 0.177538, 0.0], [0.033194, 0.966806, 0.0],
                                   [0.017083, 0.072397, 0.910520]])
            lin = arr @ srgb_to_p3.T
            return _resize(lin, long_side)
    return _resize(F.decode_srgb(np.asarray(im).astype(np.float64) / 255), long_side)


def _resize(img, long_side):
    import cv2
    s = long_side / max(img.shape[:2])
    return cv2.resize(img.astype(np.float32), (int(img.shape[1] * s), int(img.shape[0] * s)),
                      interpolation=cv2.INTER_AREA).astype(np.float64)


def align_to(src, dst):
    """Warp src (linear) onto dst (linear) with a SIFT homography; identity if they
    already line up. Returns warped src and a validity mask."""
    import cv2
    def gray(x):
        g = F.encode_srgb(x @ np.array([0.2126, 0.7152, 0.0722]))
        return cv2.createCLAHE(2.0, (8, 8)).apply((g * 255).astype(np.uint8))
    if src.shape == dst.shape:
        diff = np.mean(np.abs(gray(src).astype(float) - gray(dst).astype(float)))
        if diff < 25:
            return src, np.ones(dst.shape[:2], bool)
    sift = cv2.SIFT_create(6000)
    k1, d1 = sift.detectAndCompute(gray(src), None)
    k2, d2 = sift.detectAndCompute(gray(dst), None)
    m = cv2.BFMatcher().knnMatch(d1, d2, k=2)
    good = [a for a, b in m if a.distance < 0.75 * b.distance]
    if len(good) < 30:
        raise RuntimeError("couldn't align pair (too few matches)")
    p1 = np.float32([k1[a.queryIdx].pt for a in good])
    p2 = np.float32([k2[a.trainIdx].pt for a in good])
    H, _ = cv2.findHomography(p1, p2, cv2.RANSAC, 3.0)
    h, w = dst.shape[:2]
    out = cv2.warpPerspective(src.astype(np.float32), H, (w, h), flags=cv2.INTER_LINEAR).astype(np.float64)
    mask = cv2.warpPerspective(np.ones(src.shape[:2], np.float32), H, (w, h)) > 0.99
    return out, mask


def fit(pairs_dir, out_path, stock_path=STOCK, long_side=900, same_raw=False):
    import cv2
    from scipy.optimize import least_squares
    base = F.load_stock(stock_path)
    pairs = []
    for f in sorted(os.listdir(pairs_dir)):
        name, ext = os.path.splitext(f)
        if ext.lower() != ".dng":
            continue
        ref = next((os.path.join(pairs_dir, name + e) for e in (".jpg", ".jpeg", ".heic", ".png", ".JPG", ".HEIC")
                    if os.path.exists(os.path.join(pairs_dir, name + e))), None)
        if not ref:
            print("no reference for", f)
            continue
        target = load_reference(ref, long_side)
        lin = _resize(develop_linear(os.path.join(pairs_dir, f), max_side=2 * long_side), long_side)
        lin, mask = align_to(lin, target)
        # Ignore edges (misregistration), clipped and near-black pixels; blur away grain.
        g = cv2.GaussianBlur(target.astype(np.float32), (0, 0), 2.0).astype(np.float64)
        lin = cv2.GaussianBlur(lin.astype(np.float32), (0, 0), 2.0).astype(np.float64)
        y = g @ P3_TO_XYZ[1]
        gy = cv2.Sobel(F.encode_srgb(y).astype(np.float32), cv2.CV_32F, 1, 0) ** 2 + \
            cv2.Sobel(F.encode_srgb(y).astype(np.float32), cv2.CV_32F, 0, 1) ** 2
        ok = mask & (np.sqrt(gy) < 0.15) & (y > 0.002) & (g.max(-1) < 0.98)
        idx = np.flatnonzero(ok)
        idx = np.random.default_rng(1).choice(idx, min(len(idx), 6000), replace=False)
        pairs.append((lin.reshape(-1, 3)[idx], oklab_p3(g.reshape(-1, 3)[idx])))
        print(f"{name}: {len(idx)} samples")
    if not pairs:
        sys.exit("no pairs found")

    knobs = ["printer_r", "printer_b", "crossover_r", "crossover_b", "interlayer", "contrast", "white"]
    lum2020 = np.array([0.2627, 0.6780, 0.0593])

    def stock_from(p):
        st = json.loads(json.dumps(base))
        pr_r, pr_b, x_r, x_b, k, c, w = p[:7]
        st["printer"] = [pr_r, 0.0, pr_b]
        st["crossover"] = [x_r, 0.0, x_b]
        st["sensitivity"] = list((np.eye(3) * (1 + k) - k * lum2020[None, :]).ravel())
        for cv in st["print"]:
            cv["gamma"] = c
        st["display"] = [w, 0, 0, 0, w, 0, 0, 0, w]
        return st

    k0 = -(base["sensitivity"][1]) / lum2020[1]
    p0 = [base["printer"][0], base["printer"][2], base["crossover"][0], base["crossover"][2], k0, 1.0,
          base["display"][0]]
    lo = [-0.3, -0.3, -0.5, -0.5, 0.0, 0.6, 0.6]
    hi = [0.3, 0.3, 0.5, 0.5, 1.5, 1.6, 1.0]
    if same_raw:
        # Same capture on both sides: white balance is shared and one exposure offset
        # (where the reference puts 18% grey) applies to every pair.
        p0 += [base.get("exposure", 0.0)]; lo += [-4]; hi += [4]
    else:
        p0 += [0.0, 0.0, 0.0] * len(pairs)   # per pair: ev, temperature (r/b), tint (g)
        lo += [-4, -0.3, -0.3] * len(pairs)
        hi += [4, 0.3, 0.3] * len(pairs)

    def pair_params(p, i):
        if same_raw:
            return p[7], 0.0, 0.0
        return p[7 + 3 * i: 10 + 3 * i]

    def resid(p):
        st = stock_from(p)
        out = []
        for i, (lin, lab_t) in enumerate(pairs):
            ev, t, tint = pair_params(p, i)
            wb = np.array([2 ** t, 2 ** tint, 2 ** -t])
            x = np.clip(lin * wb * 2 ** ev @ F.SRGB_TO_REC2020.T, 0, F.SHAPER_SCALE)
            lab = oklab_p3(np.clip(F.display(F.negative_density(x, st), st), 0, 1))
            out.append(((lab - lab_t) * np.array([1.0, 1.5, 1.5])).ravel())
        return np.concatenate(out)

    r = least_squares(resid, p0, bounds=(lo, hi), x_scale="jac", max_nfev=200, verbose=1)
    for k, v in zip(knobs, r.x[:7]):
        print(f"  {k:12s} {v:+.4f}")
    rms = np.sqrt(np.mean(r.fun.reshape(-1, 3) ** 2, axis=0))
    print(f"  residual (Oklab L, a, b weighted) {rms.round(4)}")
    st = stock_from(r.x)
    if same_raw:
        st["exposure"] = float(r.x[7])
        print(f"  exposure     {r.x[7]:+.4f} stops (stored in the stock)")
    else:
        print("  per-pair exposure:", ", ".join(f"{pair_params(r.x, i)[0]:+.2f}" for i in range(len(pairs))))
    # bake the contrast multiplier into the print tables so the app's gamma stays 1
    for cv in st["print"]:
        g = cv.pop("gamma", 1.0)
        cv["x"] = [float(v) / g for v in cv["x"]]
    st["about"] = base.get("about", "") + f" Refit to {len(pairs)} reference pairs."
    st = json.loads(json.dumps(st, default=float))
    with open(out_path, "w") as f:
        json.dump(st, f, indent=1)
    print("wrote", out_path, "- now run: scripts/print-look.py export-swift")


def parity():
    import subprocess
    import tempfile
    editor = os.path.join(HERE, "..", "PointAndShoot", "Editor")
    with tempfile.TemporaryDirectory() as tmp:
        exe, out = os.path.join(tmp, "parity"), os.path.join(tmp, "out.json")
        subprocess.run(["swiftc", "-O", "-swift-version", "5", "-o", exe, os.path.join(HERE, "film-parity", "main.swift"),
                        os.path.join(editor, "FilmModel.swift"), os.path.join(editor, "FilmStock+Print.swift")], check=True)
        subprocess.run([exe, out], check=True)
        sw = json.load(open(out))
    st = F.load_stock(STOCK)
    stops = np.arange(-6, 6.01, 0.5)
    ctl = dict(contrast=0.4, saturation=0.5, crossover=-0.5, highlights=0.3, shadows=-0.4)
    neg, negd = F.negative_cube(st, "sceneLinear", 64), F.negative_cube(st, "displayReferred", 64)
    pc, pcc = F.print_cube(st, None, 48), F.print_cube(st, ctl, 48)
    i64 = [(0, 0, 0), (10, 20, 30), (40, 40, 40), (63, 63, 63), (50, 12, 33), (21, 22, 23), (5, 60, 31)]
    i48 = [(0, 0, 0), (10, 20, 30), (24, 24, 24), (47, 47, 47), (40, 9, 25), (16, 17, 18), (3, 45, 23)]
    checks = {
        "neutral": (sw["neutral"], F.neutral_response(stops, st)),
        "neutral_ctl": (sw["neutral_ctl"], F.neutral_response(stops, st, ctl)),
        "neg": (sw["neg"], [neg[b, g, r] for r, g, b in i64]),
        "negD": (sw["negD"], [negd[b, g, r] for r, g, b in i64]),
        "print": (sw["print"], [pc[b, g, r] for r, g, b in i48]),
        "print_ctl": (sw["print_ctl"], [pcc[b, g, r] for r, g, b in i48]),
    }
    worst = 0.0
    for k, (a, b) in checks.items():
        d = float(np.abs(np.array(a) - np.array(b)).max())
        worst = max(worst, d)
        print(f"  {k:12s} max diff {d:.2e}")
    if worst > 1e-5:
        sys.exit("Swift and Python disagree")
    print("parity OK")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("export-swift")
    pv = sub.add_parser("preview")
    pv.add_argument("dngs", nargs="+")
    pv.add_argument("--ev", type=float, default=0.0)
    pv.add_argument("--out", default=".")
    sub.add_parser("parity")
    ft = sub.add_parser("fit")
    ft.add_argument("pairs_dir")
    ft.add_argument("--out", default=STOCK)
    ft.add_argument("--same-raw", action="store_true",
                    help="each reference was rendered from the very same DNG (shared white balance and exposure)")
    a = ap.parse_args()
    if a.cmd == "export-swift":
        export_swift()
    elif a.cmd == "preview":
        preview(a.dngs, a.ev, a.out)
    elif a.cmd == "parity":
        parity()
    elif a.cmd == "fit":
        fit(a.pairs_dir, a.out, same_raw=a.same_raw)


if __name__ == "__main__":
    main()
