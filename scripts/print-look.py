# --- export-swift ----------------------------------------------------------------------

def _arr(v, per_line=8, indent="            "):
    items = [f"{float(x):.6g}" for x in v]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n" + ",\n".join(indent + l for l in lines) + ",\n" + indent[:-4] + "]"


def export_swift(stock_path=STOCK, out=SWIFT):
    """Writes every film stock (Print + the looks in film-looks.json) to Swift."""
    import filmlooks
    stocks = filmlooks.all_stocks(F.load_stock(stock_path))
    ind = "                "

    def curve(c, pad="            "):
        return (f"FilmCurve(\n{pad}x: {_arr(c['x'], indent=pad + '    ')},\n"
                f"{pad}y: {_arr(c['y'], indent=pad + '    ')})")

    negatives = {json.dumps(st["negative"][0], sort_keys=True) for st in stocks.values()}
    shared_neg = None
    if len(negatives) == 1 and all(all(c == st["negative"][0] for c in st["negative"]) for st in stocks.values()):
        shared_neg = stocks["print"]["negative"][0]

    def ident(sid):
        return "printLook" if sid == "print" else f"{sid}Stock"

    lines = [
        "// GENERATED by scripts/print-look.py export-swift from scripts/print-stock.json,",
        "// scripts/phromagraph-stock.json and scripts/film-looks.json. Don't edit by hand: change",
        "// the JSON and regenerate.",
        "",
        "extension FilmStock {",
        "    /// Every stock offered as a look, by id (retired stocks live in FilmStock.Legacy).",
        "    static let all: [String: FilmStock] = Dictionary(uniqueKeysWithValues: [",
        "        " + ", ".join(ident(k) for k in stocks) + ",",
        "    ].map { ($0.id, $0) })",
        "",
        "    /// The stock for a recipe's id (nil = Print, which predates stock ids). A retired id",
        "    /// gives Print here: render recipes through `FilmStock.resolved(for:)`, which knows them.",
        "    static func named(_ id: String?) -> FilmStock { all[id ?? \"print\"] ?? printLook }",
        "",
    ]
    if shared_neg:
        lines += ["    /// Vision3 5219-style negative curve (Kodak H-1-5219), shared by every stock.",
                  f"    private static let sharedNegative = {curve(shared_neg, '        ')}", ""]
    for sid, st in stocks.items():
        hs = st["halation_spread"]
        same_prn = all(c == st["print"][0] for c in st["print"])
        about = (st.get("about") or st["name"]).replace("\n", " ")
        lines += [f"    /// {st['name']}: {about}", f"    static let {ident(sid)}: FilmStock = {{"]
        if same_prn:
            lines.append(f"        let printCurve = {curve(st['print'][0])}")
        neg = "[sharedNegative, sharedNegative, sharedNegative]" if shared_neg else \
            "[" + ", ".join(curve(c) for c in st["negative"]) + "]"
        prn = "[printCurve, printCurve, printCurve]" if same_prn else "[" + ", ".join(curve(c) for c in st["print"]) + "]"
        lines += [
            "        return FilmStock(",
            f"            id: \"{sid}\",",
            f"            exposure: {float(st.get('exposure', 0.0))},",
            f"            sensitivity: {_arr(st['sensitivity'], 3, ind)},",
            f"            negative: {neg},",
            f"            print: {prn},",
            f"            printer: {[float(v) for v in st['printer']]},",
            f"            crossover: {[float(v) for v in st['crossover']]},",
            f"            crosstalk: {_arr(st['crosstalk'], 3, ind)},",
            f"            display: {_arr(st['display'], 3, ind)},",
            f"            halation: {[float(v) for v in st['halation']]},",
            "            halationSpread: .init(",
            f"                threshold: {float(hs['threshold'])}, boost: {float(hs['boost'])},",
            f"                displayThreshold: {float(hs['display_threshold'])}, displayBoost: {float(hs['display_boost'])},",
            f"                sigmas: {[float(v) for v in hs['sigmas']]}, weights: {[float(v) for v in hs['weights']]}),",
            f"            grainDensity: {float(st['grainDensity'])},",
            f"            grainChroma: {float(st['grainChroma'])},",
            f"            grainSize: {float(st['grain_size'])},",
            f"            huePreserve: {float(st.get('huePreserve', 0.0))},",
            f"            monoTone: {[float(v) for v in st.get('monoTone', [1.0, 1.0, 1.0])]},",
            f"            shadowTint: {[float(v) for v in st.get('shadowTint', [0.0, 0.0, 0.0])]},",
            f"            highlightTint: {[float(v) for v in st.get('highlightTint', [0.0, 0.0, 0.0])]}"
            + ("," if st.get("hueTwists") or st.get("dyeSaturation") else ")"),
        ]
        if st.get("hueTwists"):      # only stocks that use them: the others stay byte-identical
            tw = [f"{ind}.init(hue: {float(h)}, width: {float(w)}, rotation: {float(r)}, saturation: {float(sa)}, stops: {float(sp)})"
                  for h, w, r, sa, sp in st["hueTwists"]]
            lines.append("            hueTwists: [\n" + ",\n".join(tw) + ",\n            ]"
                         + ("," if st.get("dyeSaturation") else ")"))
        if st.get("dyeSaturation"):
            lines.append(f"            dyeSaturation: {float(st['dyeSaturation'])})")
        lines += [
            "    }()",
            "",
        ]
    lines += ["}", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(out), f"({len(stocks)} stocks)")


# --- DNG develop (like CIRAWFilter with no tone curve) ---------------------------------

def develop_linear(path, max_side=None):
    import rawpy
    from PIL import Image
    with rawpy.imread(path) as r:
        rgb = r.postprocess(gamma=(1, 1), no_auto_bright=True, output_bps=16, use_camera_wb=True,
                            output_color=rawpy.ColorSpace.sRGB, highlight_mode=rawpy.HighlightMode.Blend)
    img = rgb.astype(np.float32) / 65535.0
    try:  # DNG BaselineExposure, which CIRAWFilter applies by default
        from PIL import Image as _I
        be = _I.open(path).tag_v2.get(50730)
        if be is not None:
            img *= 2.0 ** float(be)
    except Exception:
        pass
    if max_side and max(img.shape[:2]) > max_side:
        s = max_side / max(img.shape[:2])
        h, w = int(img.shape[0] * s), int(img.shape[1] * s)
        img = np.stack([np.asarray(Image.fromarray(img[..., c]).resize((w, h), Image.BOX)) for c in range(3)], -1)
    return img.astype(np.float64)


def save_p3(img_lin_p3, path):
    from PIL import Image
    Image.fromarray((F.encode_srgb(img_lin_p3) * 255 + 0.5).astype(np.uint8)).save(path, quality=93)


def preview(paths, ev, out_dir, stock_path=STOCK):
    st = F.load_stock(stock_path)
    os.makedirs(out_dir, exist_ok=True)
    for p in paths:
        lin = develop_linear(p, max_side=2400)
        out = F.render(lin, st, exposure_ev=ev)
        name = os.path.splitext(os.path.basename(p))[0]
        save_p3(out, os.path.join(out_dir, f"{name}-print.jpg"))
        print("wrote", os.path.join(out_dir, f"{name}-print.jpg"))


